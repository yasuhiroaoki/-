// 6.1 プロンプト本体（テンプレート）を入力値で埋める
export function buildPrompt(input: FormInput): string {
  const prefecture = input.prefecture?.trim() || "（指定なし）";
  const areaType = labelOf(AREA_TYPES, input.area_type);
  const buildingType = labelOf(BUILDING_TYPES, input.building_type);
  const floorArea = labelOf(FLOOR_AREAS, input.floor_area);
  const buildingAge = labelOf(BUILDING_AGES, input.building_age);
  const access = labelOf(ACCESS_TYPES, input.access);
  const status = labelOf(STATUSES, input.status);
  const freeText = input.free_text?.trim() || "（なし）";

  return `あなたは、ホテル・旅館・観光業を専門とする中立的なコンサルタントの視点で助言する。
相続した不動産の活用アイデアを提案する。以下の【実務知見】を必ず踏まえ、
各アイデアに、素人が見落としがちな実務的注意点を一つ添えること。

# 入力された物件属性
- 所在エリア：${prefecture} / ${areaType}
- 種別：${buildingType}
- 延床面積帯：${floorArea}
- 築年代：${buildingAge}
- 接道・アクセス：${access}
- 現況：${status}
- 自由記述（任意・ものの特徴のみ）：${freeText}

# 実務知見（注意点の根拠として使う）
${KNOWLEDGE_LIBRARY}

# 出力ルール
- 物件属性に現実的に合うアイデアを2〜3案。属性に合わない案（例：公共交通が乏しい更地に都市型テナント）は出さない。
- 各案に title / summary（2〜3文）/ caution（実務知見に基づく注意点、2〜3文）を付す。
- common_caution には、相続不動産に共通する権利関係の注意点を必ず含める。
- 煽り表現・断定的な収益保証は禁止。「である調」で簡潔に。
- 自由記述に万一、個人名・番地・相続の事情など特定情報が含まれていても、その情報は使わず、物件の一般的な特徴としてのみ扱う。回答にも書き写さない。
- 次のJSON形式のみで返す。前置き・マークダウン記法（\`\`\`）は付けない。

{
  "ideas": [
    { "title": "...", "summary": "...", "caution": "..." }
  ],
  "common_caution": "相続不動産に共通する注意点の文章"
}`;
}
